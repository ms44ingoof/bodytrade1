package com.example.bodytrade;

/** Улучшения органов и конечностей за частицы жизни. Стоимость - по уровням. */
public enum Upgrade {
    STOMACH("stomach", "Желудок", "Реже хочется есть: организм сам подкармливает вас. Работает, пока желудок на месте.", 10, 25, 50),
    LIVER("liver", "Печень", "Раны затягиваются сами: здоровье восстанавливается без еды. Работает, пока печень на месте.", 10, 25, 50),
    KIDNEYS("kidneys", "Почки", "Организм очищается: 1 ур. снимает яд, 2 ур. тошноту, 3 ур. ещё и голод и слабость. Нужна хотя бы одна почка.", 8, 20, 40),
    LUNGS("lungs", "Лёгкие", "Можно намного дольше не дышать под водой (на 3 уровне воздух почти не кончается). Нужно хотя бы одно лёгкое.", 10, 25, 50),
    HEART("heart", "Сердце", "Больше здоровья: +1 сердце за уровень.", 15, 35, 70),
    LEGS("legs", "Ноги", "Бег быстрее на 8% за уровень. Нужна хотя бы одна нога или протез.", 12, 30, 60),
    ARMS("arms", "Руки", "Быстрее копаете и сильнее бьёте (+1 урон за уровень). Нужна хотя бы одна рука или протез.", 12, 30, 60),
    EYES("eyes", "Глаза", "1 ур.: видите в темноте под землёй, 2 ур.: везде. Нужен хотя бы один глаз.", 8, 25),
    SKIN("skin", "Кожа", "Толстая кожа: +2 брони за уровень.", 10, 25, 50),
    BONES("bones", "Кости", "Крепкие кости: вас труднее отбросить назад.", 8, 20, 40),
    IMMUNE("immune", "Иммунитет", "Болезни проходят в 2, 3 и 4 раза быстрее.", 10, 25, 50);

    public final String id, nom, desc;
    public final int[] costs;

    Upgrade(String id, String nom, String desc, int... costs) { this.id = id; this.nom = nom; this.desc = desc; this.costs = costs; }

    public int max() { return costs.length; }

    public static Upgrade byId(String id) {
        for (Upgrade u : values()) if (u.id.equals(id)) return u;
        return null;
    }
}
